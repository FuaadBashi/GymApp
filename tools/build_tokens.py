"""Write the app's and the studio's design tokens from design/tokens.json (redesign card R.2).

Usage: python3 -I tools/build_tokens.py [--check]
Writes GymApp/App/Tokens.swift and studio/web/tokens.css. Edit design/tokens.json, never the
outputs. With --check it writes nothing and exits 1 if either file differs from what the JSON
gives (a hand edit, or a JSON change not rebuilt); tools/check.sh runs it.
"""
import json
import sys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/tokens.json"
SWIFT = ROOT / "GymApp/App/Tokens.swift"
CSS = ROOT / "studio/web/tokens.css"
HEADER = "Generated by tools/build_tokens.py from design/tokens.json. Do not edit by hand."


def rgba(value: str) -> tuple[int, int, int, float]:
    """'#RRGGBB' or 'rgba(r,g,b,a)' as (r, g, b, alpha)."""
    if value.startswith("#") and len(value) == 7:
        return int(value[1:3], 16), int(value[3:5], 16), int(value[5:7], 16), 1.0
    m = re.fullmatch(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)", value)
    if not m:
        raise ValueError(f"Not a colour: {value}")
    r, g, b, a = m.groups()
    return int(r), int(g), int(b), float(a)


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)([A-Z])", r"-\1", name).lower()


def number(x: float) -> str:
    return f"{x:g}"


def swift(t: dict) -> str:
    out = [f"// {HEADER}", "import SwiftUI", "", "enum Tokens {"]
    for name, value in t["color"].items():
        r, g, b, a = rgba(value)
        alpha = "" if a == 1 else f", opacity: {number(a)}"
        out.append(f"    static let {name} = Color(.sRGB, red: {r} / 255, green: {g} / 255, blue: {b} / 255{alpha})")
    out += ["", "    enum Space {"] + [f"        static let {k}: CGFloat = {number(v)}" for k, v in t["space"].items()] + ["    }"]
    out += ["", "    enum Radius {"] + [f"        static let {k}: CGFloat = {number(v)}" for k, v in t["radius"].items()] + ["    }"]
    out += ["", "    enum Size {"] + [f"        static let {k}: CGFloat = {number(v)}" for k, v in t["size"].items()] + ["    }"]
    out += ["", "    /// Text roles as Dynamic Type styles."]
    out += ["    enum Text {"] + [f"        static let {k}: Font.TextStyle = .{v['ios']}" for k, v in t["type"].items() if not k.startswith("_")] + ["    }"]
    out += ["", "    /// Durations in seconds."]
    out += ["    enum Motion {"] + [f"        static let {k}: Double = {number(v['duration'])}" for k, v in t["motion"].items() if not k.startswith("_")] + ["    }"]
    out += ["}", ""]
    return "\n".join(out)


def css(t: dict) -> str:
    out = [f"/* {HEADER} */", ":root {"]
    for name, value in t["color"].items():
        out.append(f"  --color-{kebab(name)}: {value};")
    for group in ("space", "radius", "size"):
        for k, v in t[group].items():
            out.append(f"  --{group}-{kebab(k)}: {number(v)}px;")
    for k, v in t["type"].items():
        if not k.startswith("_"):
            out.append(f"  --type-{kebab(k)}: {number(v['size'])}px;")
    for k, v in t["motion"].items():
        if not k.startswith("_"):
            out.append(f"  --motion-{kebab(k)}: {number(v['duration'])}s;")
    out += ["}", ""]
    return "\n".join(out)


def main() -> None:
    tokens = json.loads(SOURCE.read_text())
    outputs = {SWIFT: swift(tokens), CSS: css(tokens)}
    if "--check" in sys.argv:
        stale = [str(path.relative_to(ROOT)) for path, text in outputs.items()
                 if not path.exists() or path.read_text() != text]
        if stale:
            print("Not from design/tokens.json: " + ", ".join(stale), file=sys.stderr)
            sys.exit(1)
        return
    for path, text in outputs.items():
        path.write_text(text)


if __name__ == "__main__":
    main()
